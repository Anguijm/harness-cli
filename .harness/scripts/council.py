def extract_score(text: str) -> int | None:
    for line in text.splitlines():
        s = line.strip().lower()
        if s.startswith("score:"):
            tail = s.split(":", 1)[1].strip()
            tail = tail.split("/")[0].split(" ")[0].strip()
            try:
                return int(float(tail))
            except ValueError:
                return None
    return None


# --- Verification-scaling helpers (pure; unit-tested in test/) --------------

def worst_case_calls(n_personas: int, repeat_k: int, max_retries: int) -> int:
    """Worst-case Gemini calls for a run: every reviewer runs K times and the
    lead runs once, each exhausting its retry budget."""
    k = max(1, repeat_k)
    per_call = max_retries + 1
    return n_personas * k * per_call + per_call


def expected_score(dist: list[tuple[float, float]]) -> float | None:
    """Expectation E[score] = Σ p(v)·v / Σ p(v) over a scoring-token
    distribution (list of (value, probability)). Returns None when the
    distribution is empty or carries no probability mass (T1, Eq. 3.1)."""
    total = math.fsum(p for _, p in dist)
    if total <= 0:
        return None
    return math.fsum(v * p for v, p in dist) / total


def aggregate_scores(values: list[float | None]) -> dict | None:
    """Aggregate the K repeated-evaluation scores into mean/min/max/variance/n.
    The full distribution (not just mean/variance) is reported so a single-run
    outlier isn't masked by the average (T2; bugs-persona remediation on #11).
    Returns None when no value was parsed across the K repeats."""
    vals = [float(v) for v in values if v is not None]
    if not vals:
        return None
    n = len(vals)
    mean = math.fsum(vals) / n
    variance = math.fsum((v - mean) ** 2 for v in vals) / n if n > 1 else 0.0
    return {"mean": mean, "min": min(vals), "max": max(vals), "variance": variance, "n": n}


def score_distribution_from_response(resp, scale_max: int) -> list[tuple[float, float]] | None:
    """Extract the scoring-token probability distribution from a Gemini
    response's logprobs, or None on ANY failure (→ caller falls back to prose
    parsing). Defensive by construction: every attribute access is guarded, so
    an unexpected SDK response shape degrades to today's behavior rather than
    crashing the merge-gating council.

    Locates the score token as the first digit token that follows a 'score'
    marker in the chosen-token stream, then reads the top candidates at that
    position, keeping only integer tokens within [1, scale_max].
    """
    try:
        result = resp.candidates[0].logprobs_result
        chosen = list(result.chosen_candidates)
        tops = list(result.top_candidates)
    except Exception:  # noqa: BLE001 — any shape mismatch → fall back to prose.
        return None
    if not chosen or not tops or len(tops) < len(chosen):
        return None

    score_pos = None
    seen_marker = False
    acc = ""
    for i, cand in enumerate(chosen):
        tok = getattr(cand, "token", None) or ""
        if seen_marker and tok.strip().isdigit():
            score_pos = i
            break
        acc += tok
        if not seen_marker and "score" in acc.lower():
            seen_marker = True
    if score_pos is None:
        return None

    dist: list[tuple[float, float]] = []
    try:
        candidates = tops[score_pos].candidates
    except Exception:  # noqa: BLE001
        return None
    for c in candidates:
        tok = (getattr(c, "token", None) or "").strip()
        logp = getattr(c, "log_probability", None)
        if logp is None or not tok.isdigit():
            continue
        value = int(tok)
        if 1 <= value <= scale_max:
            dist.append((float(value), math.exp(logp)))
    return dist or None


def _logprobs_config(granularity: int):
    """A GenerateContentConfig requesting the top-`granularity` scoring-token
    logprobs (Gemini caps at 20), or None when granularity<=1 or the SDK types
    aren't importable (→ caller stays on the plain-text prose path)."""
    if granularity <= 1:
        return None
    try:
        from google.genai import types
    except Exception:  # noqa: BLE001
        return None
    return types.GenerateContentConfig(
        response_logprobs=True,
        logprobs=min(int(granularity), 20),
    )


def score_persona(
    client,
    model: str,
    prompt: str,
    budget: "RequestBudget",
    granularity: int,
    repeat_k: int,
) -> tuple[str, dict | None, str]:
    """Run one persona's critique `repeat_k` times and aggregate its score.

    Returns (critique_text, distribution, path):
      - critique_text — the first repeat's full critique (shown in the report).
      - distribution  — aggregate_scores() over the K repeats, or None.
      - path — how the representative score was read, surfaced in the report so
        a degraded run is visible to the human, not just a log line:
          'logprob'        continuous, from scoring-token logits (T1)
          'prose'          parsed the 'Score:' line (logprobs not requested)
          'prose_fallback' logprobs requested but unreadable — degraded signal
          'malformed'      no score found at all
    """
    config = _logprobs_config(granularity)
    values: list[float | None] = []
    paths: list[str] = []
    first_text: str | None = None
    for _ in range(max(1, repeat_k)):
        text, resp = call_gemini_raw(client, model, prompt, budget, config=config)
        if first_text is None:
            first_text = text
        dist = (
            score_distribution_from_response(resp, SCORE_SCALE_MAX)
            if (config is not None and resp is not None)
            else None
        )
        if dist:
            values.append(expected_score(dist))
            paths.append("logprob")
            continue
        prose = extract_score(text)
        if prose is not None:
            values.append(float(prose))
            paths.append("prose_fallback" if config is not None else "prose")
        else:
            paths.append("malformed")
    agg = aggregate_scores(values)
    # Representative path = the most informative one that actually fired.
    for pref in ("logprob", "prose", "prose_fallback", "malformed"):
        if pref in paths:
            path = pref
            break
    else:
        path = "malformed"
    return first_text or "(empty response)", agg, path


def update_session_state_council(scores: dict[str, int | None], source_label: str) -> None:
    state: dict = {}
    if SESSION_STATE.exists():
        try:
            state = json.loads(SESSION_STATE.read_text() or "{}")
        except json.JSONDecodeError:
            state = {}
    state["last_council"] = {
        "ts": datetime.now(timezone.utc).isoformat(timespec="seconds"),
        "source": source_label,
        "scores": scores,
    }
    SESSION_STATE.write_text(json.dumps(state, indent=2) + "\n")


def main() -> int:
    parser = argparse.ArgumentParser(description="Gemini council runner.")
    parser.add_argument("--plan", help="Path to an active_plan.md to review.")
    parser.add_argument("--diff", action="store_true", help="Review git diff instead of a plan file.")
    parser.add_argument("--base", default="origin/main", help="Diff base (default origin/main).")
    parser.add_argument("--model", default=DEFAULT_MODEL, help="Gemini model ID.")
    parser.add_argument(
        "--granularity",
        type=int,
        default=DEFAULT_GRANULARITY,
        metavar="G",
        help="Scoring-token logprobs to read; G>1 enables continuous scoring "
        "(env HARNESS_GRANULARITY, default 1 = today's argmax behavior).",
    )
    parser.add_argument(
        "--repeat-k",
        type=int,
        default=DEFAULT_REPEAT_K,
        dest="repeat_k",
        metavar="K",
        help="Repeated evaluations per persona, averaged for variance reduction "
        "(env HARNESS_REPEAT_K, default 1). K>1 multiplies API calls.",
    )
    parser.add_argument(
        "--allow-untracked",
        action="store_true",
        help="Allow council to run against an untracked or dirty plan file (escape hatch; default off).",
    )
    parser.add_argument(
        "--pr-number",
        type=int,
        default=None,
        metavar="N",
        help="PR number to fetch prior-round context from (enables cross-round memory for round 2+).",
    )
    args = parser.parse_args()
    # Both scaling knobs are floored at 1: <1 is meaningless and would break the
    # budget math and the repeat loop.
    args.granularity = max(1, args.granularity)
    args.repeat_k = max(1, args.repeat_k)

    check_halt()

    api_key = os.environ.get("GEMINI_API_KEY")
    if not api_key:
        die(
            "GEMINI_API_KEY not set. Export it in your shell (see .harness/README.md).\n"
            "Example: export GEMINI_API_KEY=...",
            code=3,
        )

    try:
        from google import genai
    except ImportError:
        die(
            "google-genai not installed.\n"
            "Run: pip install -r .harness/scripts/requirements.txt",
            code=4,
        )

    source_label, source_text = get_plan_text(args)
    personas = load_personas()

    # Pessimistic pre-flight budget check: refuse to start a run that
    # cannot complete in the worst case (every call exhausts its retry
    # budget). Without this, partial reviews can post mid-run aborts.
    # Caught by the council on sportsdata #66 round 2.
    worst_case = worst_case_calls(len(personas), args.repeat_k, MAX_RETRIES)
    if worst_case > CALL_CAP:
        die(
            f"Worst-case calls required ({worst_case}) exceed budget cap ({CALL_CAP}).\n"
            f"  personas={len(personas)}, lead=1, repeat_k={args.repeat_k}, max_retries={MAX_RETRIES}.\n"
            f"  (each reviewer runs repeat_k× and the lead once, each with retries.)\n"
            f"To fix, choose one:\n"
            f"  - Lower --repeat-k / HARNESS_REPEAT_K (K>1 multiplies calls).\n"
            f"  - Lower MAX_RETRIES in .harness/scripts/council.py.\n"
            f"  - Raise CALL_CAP in .harness/scripts/council.py (also raise MONTHLY_CAP in council.yml).\n"
            f"  - Disable a persona by renaming <name>.md to <name>.md.disabled.",
            code=5,
        )

    client = genai.Client(api_key=api_key)

    checklist = load_security_checklist()
    budget = RequestBudget(CALL_CAP)

    prior_context = ""
    prior_context_fetch_error = False
    if args.pr_number:
        print(f"[council] Fetching prior-round context for PR #{args.pr_number}...")
        prior_context, prior_context_fetch_error = fetch_prior_round_context(args.pr_number)
        if prior_context:
            print(f"[council] Prior round context loaded ({len(prior_context)} chars).")
        elif prior_context_fetch_error:
            print(f"[council] WARNING: prior-round context fetch failed; review proceeds without history.", file=sys.stderr)
        else:
            print(f"[council] No prior round found — running as first round.")

    print(f"[council] Model: {args.model}")
    print(f"[council] Source: {source_label}")
    print(f"[council] Request budget: {CALL_CAP} (includes retries)")
    print(
        f"[council] Scaling: granularity={args.granularity} "
        f"({'continuous' if args.granularity > 1 else 'argmax'}), "
        f"repeat_k={args.repeat_k}"
    )
    print(f"[council] Dispatching {len(personas)} angle reviews in parallel...")

    critiques: dict[str, str] = {}
    distributions: dict[str, dict | None] = {}
    score_paths: dict[str, str] = {}
    with ThreadPoolExecutor(max_workers=min(len(personas), 6)) as pool:
        futures = {}
        for name, body in personas:
            extra = (
                f"\nSECURITY CHECKLIST (for Security reviewer):\n{checklist}\n"
                if name == "security"
                else ""
            )
            prompt = build_prompt(body, source_label, source_text, extra=extra, prior_context=prior_context)
            futures[
                pool.submit(
                    score_persona, client, args.model, prompt, budget, args.granularity, args.repeat_k
                )
            ] = name
        for fut in as_completed(futures):
            name = futures[fut]
            critiques[name], distributions[name], score_paths[name] = fut.result()
            print(f"[council]   {name}: done ({score_paths[name]})")

    # Representative score per persona: the mean across the K repeats, rounded
    # to an int to keep the Scores table and yolo_log / session_state consumers
    # backward-compatible (at granularity=1, repeat_k=1 this equals the old
    # single argmax integer exactly). The full continuous distribution lives in
    # `distributions` and is rendered in the report.
    scores = {
        name: (int(round(agg["mean"])) if agg else None)
        for name, agg in distributions.items()
    }

    print("[council] Running Lead Architect synthesis...")
    lead_body = load_lead()
    synthesis_payload = (
        f"ORIGINAL SOURCE: {source_label}\n\n"
        f"{source_text}\n\n"
        f"---\nREVIEWER CRITIQUES\n"
    )
    for name, text in sorted(critiques.items()):
        synthesis_payload += f"\n### {name}\n{text}\n"
    # Lead Architect sees prior context before the new critiques so they can
    # surface contradictions as they synthesize.
    if prior_context:
        synthesis_payload = f"{prior_context}\n\n---\n\n" + synthesis_payload
    lead_prompt = build_prompt(lead_body, source_label, synthesis_payload)
    synthesis = call_gemini(client, args.model, lead_prompt, budget)
    used, cap = budget.snapshot()
    print(f"[council] Requests consumed: {used}/{cap}")

    ts = datetime.now(timezone.utc).isoformat(timespec="seconds")
    report = [
        f"# Council report — {ts}",
        "",
        f"**Source:** {source_label}",
        f"**Requests:** {used}/{cap}",
        "",
    ]
    if prior_context_fetch_error and args.pr_number:
        report += [
            f"> ⚠️ **Prior-round context unavailable** — `gh api` fetch for PR #{args.pr_number} failed.",
            f"> Reviewers had no history of prior remediations. This review may re-raise already-addressed concerns.",
            "",
        ]
    report += [
        "## Scores",
    ]
    for name in sorted(critiques):
        score = scores[name]
        report.append(f"- `{name}`: {score if score is not None else 'n/a'}")
    report.append("")
    # Continuous-scoring detail: only emitted when a scaling knob is on, so the
    # default (granularity=1, repeat_k=1) report is byte-identical to before.
    if args.granularity > 1 or args.repeat_k > 1:
        report.append("## Continuous scores")
        report.append(
            f"_granularity={args.granularity}, repeated evaluations={args.repeat_k} "
            f"— path shows how each score was read (logprob = continuous)._"
        )
        for name in sorted(distributions):
            agg = distributions[name]
            path = score_paths.get(name, "?")
            if agg:
                report.append(
                    f"- `{name}` [{path}]: mean {agg['mean']:.2f} "
                    f"(min {agg['min']:.2f}, max {agg['max']:.2f}, "
                    f"var {agg['variance']:.3f}, n={agg['n']})"
                )
            else:
                report.append(f"- `{name}` [{path}]: no score parsed")
        report.append("")
    report.append("## Lead Architect synthesis")
    report.append("")
    report.append(synthesis)
    report.append("")
    report.append("## Raw critiques")
    for name in sorted(critiques):
        report.append("")
        report.append(f"### {name}")
        report.append("")
        report.append(critiques[name])

    LAST_COUNCIL.write_text("\n".join(report) + "\n")
    append_log(
        {
            "event": "council_run",
            "source": source_label,
            "model": args.model,
            "scores": scores,
            "granularity": args.granularity,
            "repeat_k": args.repeat_k,
            "score_paths": score_paths,
            "score_distributions": distributions,
            "requests_used": used,
            "requests_cap": cap,
        }
    )
    update_session_state_council(scores, source_label)

    print(f"[council] Report written to {LAST_COUNCIL.relative_to(REPO_ROOT)}")
    print()
    print("=" * 72)
    print("LEAD ARCHITECT SYNTHESIS")
    print("=" * 72)
    print(synthesis)
    return 0


if __name__ == "__main__":
    sys.exit(main())
